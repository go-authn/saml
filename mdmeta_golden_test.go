package saml

import (
	"crypto/x509"
	"encoding/pem"
	"errors"
	"flag"
	"os"
	"testing"
)

var updateGolden = flag.Bool("update-golden", false, "rewrite testdata/sp-metadata-*.golden.xml")

// goldenSP is an SP whose certificate is fixed, so that its metadata is the
// same bytes on every run.
func goldenSP(t *testing.T) *SP {
	t.Helper()
	c, err := goldenSPCert()
	if err != nil {
		t.Fatal(err)
	}
	return &SP{EntityID: spEntity, ACS: acsURL, Cert: c}
}

func goldenSPCert() (*x509.Certificate, error) {
	b, err := os.ReadFile("testdata/sp-golden-cert.pem")
	if err != nil {
		return nil, err
	}
	blk, _ := pem.Decode(b)
	if blk == nil {
		return nil, errors.New("testdata/sp-golden-cert.pem holds no certificate")
	}
	return x509.ParseCertificate(blk.Bytes)
}

// TestMetadataGoldenWithoutNewBlocks: a Description that sets none of the
// Organization, Contacts, Logos, InformationURLs or PrivacyStatementURLs
// fields yields the bytes v0.7.3 wrote -- the golden files were generated by
// v0.7.3, before those fields existed.
func TestMetadataGoldenWithoutNewBlocks(t *testing.T) {
	for name, d := range map[string]Description{
		"minimal": {Names: map[string]string{"en": "OIDC bridge"}},
		"full": {
			Names:            map[string]string{"fr": "Passerelle OIDC", "en": "OIDC bridge"},
			Descriptions:     map[string]string{"fr": "Connexion fédérée", "en": "Federated sign-in"},
			InformationURL:   "https://bridge.example.org/",
			PrivacyStatement: "https://bridge.example.org/privacy",
			Discovery:        "https://bridge.example.org/saml/disco",
			Technical:        "noc@example.org",
			Attributes:       []string{SubjectID, EduPersonPrincipalName, Mail},
		},
	} {
		t.Run(name, func(t *testing.T) {
			got, err := goldenSP(t).Metadata(d)
			if err != nil {
				t.Fatal(err)
			}
			file := "testdata/sp-metadata-" + name + ".golden.xml"
			if *updateGolden {
				if err := os.WriteFile(file, got, 0o644); err != nil {
					t.Fatal(err)
				}
				return
			}
			want, err := os.ReadFile(file)
			if err != nil {
				t.Fatal(err)
			}
			if string(got) != string(want) {
				t.Errorf("the metadata differs from %s:\n%s", file, got)
			}
		})
	}
}
